function isPeripheralTopic(normalized) {
  return peripheralKeywords.some((kw) => normalized.includes(kw));
}

export function pickMockResponse(userText) {
  const normalized = userText.toLowerCase().trim();

  for (const rule of keywordRules) {
    if (rule.keywords.some((kw) => normalized.includes(kw))) {
      return rule.text;
    }
  }

  if (!isPeripheralTopic(normalized)) {
    return offTopicRedirectMessage();
  }

  return (
    'Уточните, пожалуйста, какой тип устройства вас интересует (клавиатура, мышь, монитор, наушники и т.д.) и для каких задач — подберу варианты по характеристикам.'
  );
}

export function randomTypingDelay() {
  return 800 + Math.floor(Math.random() * 700);
}
